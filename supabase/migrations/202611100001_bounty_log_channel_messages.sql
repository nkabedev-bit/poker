-- Посты в канале клуба о вылете с финального стола.
--
-- Вылет с финального стола (до 5-го места) приложение публикует в канал, а вместе с
-- 5-м местом — опрос «кто займет топ 1?». Номера этих сообщений запоминаются в строке
-- вылета, чтобы отмена вылета (ошибка или «вернуть в игру») удаляла их из канала.
--
-- Без миграции посты публикуются как обычно, но при отмене вылета остаются в канале:
-- их придётся удалить руками.
--
-- Применять вручную. Повторный запуск безопасен.

alter table public.bounty_log
  add column if not exists channel_message_ids bigint[];
