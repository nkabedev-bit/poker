-- Любимая рука игрока.
--
-- Игрок со статусом MEMBER и выше выбирает в мини-аппе две карты, которые считает
-- своими. Они рисуются на его аватарке везде внутри приложения: профиль, рейтинг,
-- столы, результаты игр. На экран в зале не выводятся.
--
-- Хранится строкой из двух карт: ранг (2–9, T = 10, J, Q, K, A) и масть (s ♠, h ♥,
-- d ♦, c ♣), например 'QsTs' — дама и десятка пик. Порядок — как игрок выбрал.
-- Проверку статуса делает приложение; база держит только формат и то, что карты
-- разные.
--
-- Приложение читает колонку отдельными запросами и переживает её отсутствие: пока
-- миграция не применена, рук просто не видно, а сохранение отвечает, что нужна
-- миграция.
--
-- Применять вручную в Supabase SQL editor. Повторный запуск безопасен.

alter table public.client_bot_users
  add column if not exists favorite_hand text
    constraint client_bot_users_favorite_hand_format check (
      favorite_hand ~ '^[2-9TJQKA][shdc][2-9TJQKA][shdc]$'
      and substr(favorite_hand, 1, 2) <> substr(favorite_hand, 3, 2)
    );
