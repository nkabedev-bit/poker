-- Размер финального стола игры.
--
-- Финальный стол — столько мест, сколько стоит за столом в настройках турнира: при
-- 9 макс это места 1–9, при 10 макс — 1–10. На финише приложение пишет размер в каждую
-- строку результата игры, и «Финалки» в профиле, серии за финальным столом и
-- достижения считаются по нему.
--
-- Старые игры остаются без него (null) и считаются как раньше — по 9 мест.
--
-- Без миграции приложение работает как раньше: размер не пишется, финальный стол — 9.
--
-- Применять вручную. Повторный запуск безопасен.

alter table public.tournament_results
  add column if not exists final_table_size smallint
    constraint tournament_results_final_table_size_range
      check (final_table_size between 1 and 10);
