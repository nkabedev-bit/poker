-- Согласие игрока с правилами клуба.
--
-- При входе в мини-апп игрок видит памятку: в спорных ситуациях клуб руководствуется
-- своими правилами (PDF лежит в public/rules). Игрок отмечает «С правилами ознакомлен»,
-- и время отметки сохраняется здесь — по нему клуб может показать, что игрок с
-- правилами согласился.
--
-- Когда правила обновляются, приложение поднимает дату редакции в lib/client/club-rules.ts:
-- отметка раньше этой даты считается устаревшей, и памятка всплывает снова.
--
-- Приложение читает колонку отдельным запросом и переживает её отсутствие: пока
-- миграция не применена, памятка не показывается.
--
-- Повторный запуск безопасен.

alter table public.client_bot_users
  add column if not exists rules_accepted_at timestamptz;
